class Countdown:  # Объявляем собственный итератор обратного отсчёта.
    def __init__(self, n: int) -> None:  # Определяем конструктор, принимающий начальное число отсчёта.
        if not isinstance(n, int):  # Проверяем, что отсчёт задан целым числом.
            raise TypeError("Начальное значение отсчёта должно быть целым числом.")  # Явно сообщаем о неверном типе аргумента.
        self.current = n  # Сохраняем текущее значение, которое будет выдано итератором.

    def __iter__(self) -> "Countdown":  # Делаем объект итерируемым и возвращаем сам итератор.
        return self  # Возвращаем этот объект, у которого реализован метод __next__.

    def __next__(self) -> int:  # Определяем получение следующего значения последовательности.
        if self.current < 1:  # Проверяем, остались ли положительные числа для выдачи.
            raise StopIteration  # Завершаем итерацию после выдачи единицы.
        value = self.current  # Запоминаем значение, которое нужно вернуть сейчас.
        self.current -= 1  # Уменьшаем счётчик для следующего вызова метода.
        return value  # Возвращаем очередное число обратного отсчёта.


def fibonacci(n: int) -> Iterator[int]:  # Объявляем генератор первых n чисел последовательности Фибоначчи.
    if not isinstance(n, int):  # Проверяем, что количество чисел является целым.
        raise TypeError("Количество чисел Фибоначчи должно быть целым.")  # Сообщаем о неверном типе аргумента.
    if n < 0:  # Проверяем, что запрошено неотрицательное количество чисел.
        raise ValueError("Количество чисел Фибоначчи не может быть отрицательным.")  # Явно сообщаем о недопустимом количестве.
    first, second = 0, 1  # Инициализируем первые два числа последовательности.
    for _ in range(n):  # Повторяем выдачу ровно n раз.
        yield first  # Возвращаем текущее число и приостанавливаем генератор.
        first, second = second, first + second  # Переходим к следующей паре чисел Фибоначчи.


def read_decimal(prompt: str) -> Decimal:  # Объявляем помощник для безопасного ввода десятичных чисел.
    while True:  # Повторяем запрос, пока пользователь не введёт корректное число.
        raw_value = input(prompt).strip().replace(",", ".")  # Считываем значение и разрешаем запятую как десятичный разделитель.
        try:  # Начинаем преобразование строки в Decimal.
            value = Decimal(raw_value)  # Преобразуем строку в точное десятичное значение.
            if value.is_finite():  # Проверяем, что число не является NaN или бесконечностью.
                return value  # Возвращаем конечное десятичное значение.
            print("Ошибка: введите конечное число.")  # Просим пользователя не вводить бесконечность или NaN.
        except InvalidOperation:  # Перехватываем строку, которая не является корректным десятичным числом.
            print("Ошибка: введите число, например 1000 или 4,5.")  # Просим пользователя ввести значение в числовом формате.


def calculate_deposit() -> None:  # Объявляем функцию расчёта вклада с ежемесячной капитализацией.
    print("\n" + "=" * 60)  # Отделяем финансовый калькулятор от предыдущего раздела.
    print("4. ФИНАНСОВЫЙ КАЛЬКУЛЯТОР ВКЛАДА")  # Печатаем заголовок задания о вкладе.
    principal = read_decimal("Введите начальную сумму вклада: ")  # Получаем сумму вклада в формате Decimal.
    while principal < 0:  # Проверяем, что сумма вклада не отрицательна.
        print("Начальная сумма не может быть отрицательной.")  # Сообщаем о недопустимой сумме.
        principal = read_decimal("Введите начальную сумму вклада: ")  # Повторно запрашиваем сумму.
    annual_rate = read_decimal("Введите годовую процентную ставку: ")  # Получаем годовую ставку в процентах.
    while annual_rate < 0:  # Проверяем, что ставка вклада не отрицательна.
        print("Процентная ставка не может быть отрицательной.")  # Сообщаем о недопустимой ставке.
        annual_rate = read_decimal("Введите годовую процентную ставку: ")  # Повторно запрашиваем ставку.
    years = read_decimal("Введите срок вклада в годах: ")  # Получаем срок вклада в годах, допускающий дробную часть.
    while years < 0:  # Проверяем, что срок вклада не отрицателен.
        print("Срок вклада не может быть отрицательным.")  # Сообщаем о недопустимом сроке.
        years = read_decimal("Введите срок вклада в годах: ")  # Повторно запрашиваем срок.
    monthly_rate = annual_rate / (Decimal(12) * Decimal(100))  # Переводим годовую ставку в десятичную месячную ставку.
    number_of_months = Decimal(12) * years  # Вычисляем количество месяцев согласно заданной формуле.
    final_amount = principal * (Decimal(1) + monthly_rate) ** number_of_months  # Рассчитываем итоговую сумму по формуле ежемесячной капитализации.
    cent = Decimal("0.01")  # Задаём шаг округления денежных значений до одной копейки.
    rounded_amount = final_amount.quantize(cent, rounding=ROUND_HALF_UP)  # Округляем итоговую сумму до копеек обычным финансовым правилом.
    profit = (final_amount - principal).quantize(cent, rounding=ROUND_HALF_UP)  # Рассчитываем и округляем прибыль вклада до копеек.
    print(f"Сумма вклада в конце срока: {rounded_amount:.2f} руб.")  # Выводим итоговую сумму с двумя знаками после запятой.
    print(f"Общая прибыль: {profit:.2f} руб.")  # Выводим прибыль сверх первоначальной суммы с точностью до копеек.


def calculate_fraction_operations() -> None:  # Объявляем функцию выполнения арифметических операций с дробями.
    print("\n" + "=" * 60)  # Отделяем задание с дробями от финансового калькулятора.
    print("5. ОПЕРАЦИИ С ДРОБЯМИ")  # Печатаем заголовок задания с модулем fractions.
    first_fraction = Fraction(3, 4)  # Создаём дробь три четверти.
    second_fraction = Fraction(5, 6)  # Создаём дробь пять шестых.
    print(f"Первая дробь: {first_fraction}")  # Выводим первую дробь в несократимом виде.
    print(f"Вторая дробь: {second_fraction}")  # Выводим вторую дробь в несократимом виде.
    print(f"Сложение: {first_fraction} + {second_fraction} = {first_fraction + second_fraction}")  # Складываем дроби и выводим сокращённый результат.
    print(f"Вычитание: {first_fraction} - {second_fraction} = {first_fraction - second_fraction}")  # Вычитаем вторую дробь из первой и выводим результат.
    print(f"Умножение: {first_fraction} * {second_fraction} = {first_fraction * second_fraction}")  # Перемножаем дроби и выводим результат.
    print(f"Деление: {first_fraction} / {second_fraction} = {first_fraction / second_fraction}")  # Делим первую дробь на вторую и выводим результат.


def format_date(value: datetime) -> str:  # Объявляем функцию форматирования даты русским текстом.
    month_name = MONTH_NAMES[value.month - 1]  # Получаем русское название месяца по его номеру.
    return f"Сегодня {value.day:02d} {month_name} {value.year} года, время: {value:%H:%M}"  # Возвращаем дату и время в требуемом формате.


def next_birthday_date(birthday: date, today: date) -> date:  # Объявляем функцию поиска ближайшего дня рождения начиная с сегодняшнего дня.
    next_year = today.year  # Сначала рассматриваем текущий календарный год.
    while True:  # Повторяем поиск, чтобы корректно обработать день рождения 29 февраля.
        try:  # Пытаемся создать дату дня рождения в рассматриваемом году.
            candidate = birthday.replace(year=next_year)  # Сохраняем день и месяц рождения, заменяя год на рассматриваемый.
        except ValueError:  # Перехватываем невозможную дату 29 февраля в невисокосном году.
            candidate = date(next_year, 3, 1)  # В невисокосный год считаем ближайшей датой 1 марта.
        if candidate >= today:  # Проверяем, наступил ли кандидат сегодня или позднее.
            return candidate  # Возвращаем ближайшую дату дня рождения.
        next_year += 1  # Переходим к следующему году, если день рождения в этом году уже прошёл.


def read_birthday() -> date:  # Объявляем помощник ввода даты рождения в формате день.месяц.год.
    while True:  # Повторяем запрос, пока дата не будет введена правильно.
        raw_date = input("Введите дату рождения в формате ДД.ММ.ГГГГ: ").strip()  # Считываем строку с датой рождения.
        try:  # Начинаем разбор даты с проверкой реальности календарного дня.
            return datetime.strptime(raw_date, "%d.%m.%Y").date()  # Преобразуем введённую дату в объект date и возвращаем её.
        except ValueError:  # Перехватываем неправильный формат или несуществующую дату.
            print("Ошибка: введите существующую дату в формате ДД.ММ.ГГГГ.")  # Просим повторить ввод в правильном формате.


def calculate_dates() -> None:  # Объявляем функцию вывода текущей даты и расчёта дней рождения.
    print("\n" + "=" * 60)  # Отделяем календарное задание от предыдущего раздела.
    print("6. ДАТА, ВРЕМЯ И ДНИ РОЖДЕНИЯ")  # Печатаем заголовок задания с модулем datetime.
    current_datetime = datetime.now()  # Получаем текущие локальные дату и время.
    today = current_datetime.date()  # Выделяем текущую календарную дату из значения даты и времени.
    print(format_date(current_datetime))  # Выводим текущий момент в требуемом русскоязычном формате.
    print(f"Текущая дата: {today:%d.%m.%Y}")  # Выводим отдельно текущую дату в числовом формате.
    print(f"Текущее время: {current_datetime:%H:%M:%S}")  # Выводим отдельно текущее время с секундами.
    birthday = read_birthday()  # Получаем корректную дату рождения пользователя.
    if birthday > today:  # Проверяем, не введена ли дата рождения в будущем.
        print("Дата рождения не может быть позже сегодняшнего дня.")  # Сообщаем об ошибочной будущей дате рождения.
        return  # Завершаем расчёт календарного задания для некорректной даты.
    days_since_birth = (today - birthday).days  # Вычисляем количество прошедших дней с даты рождения.
    upcoming_birthday = next_birthday_date(birthday, today)  # Находим ближайшую дату дня рождения, которая ещё не прошла.
    days_until_birthday = (upcoming_birthday - today).days  # Вычисляем количество дней до ближайшего дня рождения.
    print(f"Дней с момента рождения: {days_since_birth}")  # Выводим полное число дней со дня рождения.
    print(f"Дней до следующего дня рождения: {days_until_birthday}")  # Выводим число дней до ближайшего дня рождения.


