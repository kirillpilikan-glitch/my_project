"""Создание аргументов и запуск консольного приложения статистики."""  # Докстринг описывает назначение модуля командной строки.

import argparse  # Импортируем стандартную библиотеку для разбора аргументов командной строки.
from collections.abc import Sequence  # Импортируем тип последовательности для аннотации аргументов запуска.

from lab5_app import __version__  # Получаем версию пакета для опции --version.
from lab5_app.statistics import calculate_statistics  # Импортируем вычислительную функцию из отдельного модуля.


def build_parser() -> argparse.ArgumentParser:  # Объявляем функцию создания настроенного парсера аргументов.
    (  # Начинаем многострочный docstring настройки парсера.
        "Создаёт парсер аргументов консольного приложения.\n"  # Кратко описываем назначение функции.
        "\n"  # Отделяем описание от результата.
        "Returns:\n"  # Начинаем раздел результата.
        "    argparse.ArgumentParser: Парсер аргументов чисел и версии.\n"  # Документируем возвращаемый парсер.
        "\n"  # Отделяем результат от исключений.
        "Raises:\n"  # Начинаем раздел исключений.
        "    Прикладные исключения не возникают при создании парсера.\n"  # Указываем отсутствие ожидаемых ошибок.
    )  # Python распознаёт объединённые строки как docstring функции.
    parser = argparse.ArgumentParser(  # Создаём парсер, который автоматически формирует справку для пользователя.
        prog="lab5-app",  # Задаём короткое имя программы в сообщениях справки.
        description="Рассчитать описательную статистику для набора чисел.",  # Объясняем назначение программы в справке.
    )  # Завершаем настройку основного парсера.
    parser.add_argument(  # Регистрируем обязательный позиционный аргумент с исходными числами.
        "numbers",  # Называем позиционный аргумент numbers.
        metavar="ЧИСЛО",  # Указываем понятное имя одного значения в справке.
        nargs="+",  # Требуем одно или несколько значений.
        type=float,  # Преобразуем каждое значение командной строки в число с плавающей точкой.
        help="Одно или несколько чисел для анализа.",  # Объясняем назначение списка чисел.
    )  # Завершаем настройку позиционного аргумента.
    parser.add_argument(  # Регистрируем опцию вывода версии приложения.
        "--version",  # Задаём имя флага версии в командной строке.
        action="version",  # Настраиваем печать версии и немедленное завершение программы.
        version=f"%(prog)s {__version__}",  # Формируем сообщение версии из имени программы и версии пакета.
        help="Показать версию приложения и завершить работу.",  # Объясняем назначение флага версии.
    )  # Завершаем настройку опции версии.
    return parser  # Возвращаем настроенный парсер вызывающему коду.


def main(argv: Sequence[str] | None = None) -> int:  # Объявляем функцию входа, принимающую необязательные аргументы командной строки.
    (  # Начинаем многострочный docstring входной функции CLI.
        "Разбирает аргументы и выводит рассчитанную статистику.\n"  # Кратко описываем основное действие функции.
        "\n"  # Отделяем описание от аргументов.
        "Args:\n"  # Начинаем раздел входных параметров.
        "    argv (Sequence[str] | None): Аргументы без имени программы или None для sys.argv.\n"  # Документируем список аргументов.
        "\n"  # Отделяем параметры от результата.
        "Returns:\n"  # Начинаем раздел результата.
        "    int: Код завершения 0 после успешного вывода статистики.\n"  # Документируем успешный код завершения.
        "\n"  # Отделяем результат от исключений.
        "Raises:\n"  # Начинаем раздел исключений.
        "    SystemExit: argparse обрабатывает --help, --version или ошибочные аргументы.\n"  # Документируем автоматическое завершение парсера.
    )  # Python распознаёт объединённые строки как docstring функции.
    parser = build_parser()  # Создаём парсер, содержащий описание всех аргументов приложения.
    args = parser.parse_args(argv)  # Разбираем переданные аргументы или аргументы текущего процесса.
    try:  # Начинаем обработку возможной ошибки входных данных статистики.
        result = calculate_statistics(args.numbers)  # Вычисляем показатели для чисел, разобранных парсером.
    except ValueError as error:  # Перехватываем ошибку пустой или не конечной последовательности.
        parser.error(str(error))  # Показываем пояснение и справку, завершая программу с ошибочным кодом.
    print("Результаты анализа:")  # Печатаем заголовок таблицы результатов.
    print(f"Количество: {int(result['count'])}")  # Выводим количество значений без незначащей дробной части.
    print(f"Сумма: {result['sum']:g}")  # Выводим сумму без лишних завершающих нулей.
    print(f"Среднее: {result['mean']:g}")  # Выводим среднее арифметическое без лишних завершающих нулей.
    print(f"Медиана: {result['median']:g}")  # Выводим медиану без лишних завершающих нулей.
    print(f"Минимум: {result['min']:g}")  # Выводим минимальное значение без лишних завершающих нулей.
    print(f"Максимум: {result['max']:g}")  # Выводим максимальное значение без лишних завершающих нулей.
    return 0  # Сообщаем операционной системе об успешном завершении приложения.
