"""Вычисление базовых статистических характеристик числовых данных."""  # Докстринг описывает функции этого модуля.

import math  # Импортируем математические проверки для выявления бесконечных значений и NaN.
from statistics import mean, median  # Импортируем стандартные реализации среднего и медианы.
from collections.abc import Sequence  # Импортируем тип последовательности для аннотации входных данных.


def calculate_statistics(numbers: Sequence[float]) -> dict[str, int | float]:  # Объявляем функцию расчёта показателей числовой последовательности.
    (  # Начинаем многострочный docstring расчёта статистики.
        "Вычисляет основные статистические характеристики набора чисел.\n"  # Кратко описываем назначение функции.
        "\n"  # Отделяем описание от аргументов.
        "Args:\n"  # Начинаем раздел входных данных.
        "    numbers (Sequence[float]): Непустая последовательность конечных чисел.\n"  # Документируем ожидаемые числа.
        "\n"  # Отделяем параметры от результата.
        "Returns:\n"  # Начинаем раздел результата.
        "    dict[str, int | float]: Количество, сумма, среднее, медиана, минимум и максимум.\n"  # Описываем ключи возвращаемого словаря.
        "\n"  # Отделяем результат от возможных исключений.
        "Raises:\n"  # Начинаем раздел ошибок.
        "    ValueError: Если последовательность пуста или содержит NaN либо бесконечность.\n"  # Документируем условия отклонения данных.
    )  # Python распознаёт объединённые строки как docstring функции.
    if not numbers:  # Проверяем, содержит ли входная последовательность хотя бы одно число.
        raise ValueError("Для расчёта необходимо передать хотя бы одно число.")  # Возвращаем вызывающему коду понятную ошибку пустого ввода.
    if any(not math.isfinite(number) for number in numbers):  # Проверяем, что каждое значение является конечным числом.
        raise ValueError("Все значения должны быть конечными числами.")  # Запрещаем расчёты с NaN и положительной или отрицательной бесконечностью.
    return {  # Создаём и возвращаем словарь рассчитанных показателей.
        "count": len(numbers),  # Сохраняем целое количество значений в последовательности.
        "sum": float(sum(numbers)),  # Сохраняем сумму всех переданных значений.
        "mean": float(mean(numbers)),  # Сохраняем среднее арифметическое значений.
        "median": float(median(numbers)),  # Сохраняем медиану значений.
        "min": float(min(numbers)),  # Сохраняем наименьшее значение.
        "max": float(max(numbers)),  # Сохраняем наибольшее значение.
    }  # Завершаем формирование словаря результатов.
