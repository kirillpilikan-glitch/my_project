"""Решения упражнений первой лабораторной работы по основам Python."""  # Описываем назначение всего файла.

import math  # Импортируем функции вычисления факториала и произведения цифр.


def read_integer(prompt: str) -> int:  # Объявляем функцию безопасного ввода целого числа.
    while True:  # Повторяем запрос, пока не будет введено целое число.
        try:  # Начинаем проверку преобразования введённого текста.
            return int(input(prompt))  # Возвращаем введённое значение после преобразования в целое число.
        except ValueError:  # Обрабатываем текст, который невозможно преобразовать в целое число.
            print("Ошибка: введите целое число.")  # Объясняем причину ошибки и просим повторить ввод.


def read_nonnegative_integer(prompt: str) -> int:  # Объявляем функцию ввода неотрицательного целого числа.
    while True:  # Повторяем запрос, пока число не удовлетворит ограничению.
        number = read_integer(prompt)  # Используем общий помощник для проверки целочисленного ввода.
        if number >= 0:  # Проверяем, что число допустимо для факториала.
            return number  # Возвращаем корректное неотрицательное число.
        print("Ошибка: число не может быть отрицательным.")  # Сообщаем о недопустимом отрицательном значении.


def read_number_with_digits(prompt: str, digit_count: int) -> int:  # Объявляем функцию ввода числа заданной разрядности.
    lower_bound = 10 ** (digit_count - 1)  # Вычисляем наименьшее положительное число нужной разрядности.
    upper_bound = 10**digit_count  # Вычисляем исключительную верхнюю границу числа нужной разрядности.
    while True:  # Повторяем запрос, пока модуль числа не будет нужной длины.
        number = read_integer(prompt)  # Получаем целое число через проверенный помощник.
        if lower_bound <= abs(number) < upper_bound:  # Проверяем разрядность, принимая также отрицательные числа.
            return number  # Возвращаем корректно введённое число.
        print(f"Ошибка: введите число из {digit_count} цифр.")  # Объясняем, какая длина требуется.


def read_character(prompt: str) -> str:  # Объявляем функцию, запрашивающую ровно один символ.
    while True:  # Повторяем запрос, пока введено не ровно одно знакоместо.
        character = input(prompt)  # Считываем пользовательский символ без удаления пробелов.
        if len(character) == 1:  # Проверяем, что введена ровно одна буква, цифра или иной знак.
            return character  # Возвращаем корректный символ для последующих проверок.
        print("Ошибка: введите ровно один символ.")  # Просим ввести только один символ.


def main() -> None:  # Объявляем основную функцию с решениями всех заданий лабораторной работы.
    print("ЛАБОРАТОРНАЯ РАБОТА № 1")  # Выводим заголовок работы.
    print("=" * 60)  # Отделяем заголовок от первого раздела.

    print("\nЗадание 1. Проверка числа")  # Начинаем задания на проверку свойств числа.
    number = read_integer("Введите число для проверки чётности: ")  # Получаем число для проверки чётности.
    print(f"{number} {'чётное' if number % 2 == 0 else 'нечётное'}.")  # Выводим чётность по остатку от деления на два.
    number = read_integer("Введите число для проверки делимости на 5: ")  # Получаем число для проверки делимости на пять.
    print(f"{number} {'делится' if number % 5 == 0 else 'не делится'} на 5 без остатка.")  # Проверяем делимость на пять.
    number = read_integer("Введите число для проверки делимости на 7: ")  # Получаем число для проверки делимости на семь.
    print(f"{number} {'делится' if number % 7 == 0 else 'не делится'} на 7 без остатка.")  # Проверяем делимость на семь.
    number = read_integer("Введите число для проверки последней цифры 3: ")  # Получаем число для проверки последней цифры.
    print(f"{number} {'оканчивается' if abs(number) % 10 == 3 else 'не оканчивается'} на цифру 3.")  # Проверяем последнюю цифру, включая отрицательные числа.

    print("\nЗадание 2. Сравнение двух чисел")  # Начинаем задания сравнения чисел.
    first = float(input("Введите первое число: "))  # Считываем первое вещественное число для сравнений.
    second = float(input("Введите второе число: "))  # Считываем второе вещественное число для сравнений.
    print(f"Большее число: {max(first, second)}")  # Выводим большее из двух чисел.
    print(f"Меньшее число: {min(first, second)}")  # Выводим меньшее из двух чисел.
    print(f"Разница (первое минус второе): {first - second}")  # Выводим разность в порядке ввода.
    print("Числа равны." if first == second else "Числа не равны.")  # Сообщаем, совпадают ли числа.

    print("\nЗадание 3. Таблица умножения")  # Начинаем задания с таблицей умножения.
    for multiplier in range(1, 11):  # Перебираем множители от одного до десяти включительно.
        print(f"2 * {multiplier} = {2 * multiplier}")  # Выводим таблицу умножения на два.
    for multiplier in range(1, 11):  # Повторно перебираем множители для числа пять.
        print(f"5 * {multiplier} = {5 * multiplier}")  # Выводим таблицу умножения на пять.
    number = read_integer("Введите число для таблицы умножения: ")  # Запрашиваем основание пользовательской таблицы.
    for multiplier in range(1, 11):  # Перебираем множители для введённого числа.
        print(f"{number} * {multiplier} = {number * multiplier}")  # Выводим произведение числа на текущий множитель.
    for multiplier in range(1, 11):  # Повторно перебираем множители для числа десять.
        print(f"10 * {multiplier} = {10 * multiplier}")  # Выводим таблицу умножения на десять.

    print("\nЗадание 4. Сумма чисел в диапазоне")  # Начинаем задания на суммирование диапазонов.
    print(f"Сумма чисел от 1 до 10: {sum(range(1, 11))}")  # Вычисляем и выводим сумму первых десяти натуральных чисел.
    limit = read_integer("Введите N для суммы чисел от 1 до N: ")  # Получаем верхнюю границу диапазона.
    print(f"Сумма чисел от 1 до {limit}: {sum(range(1, limit + 1))}")  # Суммируем целые числа включительно до N.
    limit = read_integer("Введите N для суммы чётных чисел: ")  # Получаем границу диапазона чётных чисел.
    even_sum = sum(number for number in range(1, limit + 1) if number % 2 == 0)  # Складываем только чётные числа от одного до N.
    print(f"Сумма чётных чисел от 1 до {limit}: {even_sum}")  # Выводим рассчитанную сумму чётных чисел.
    limit = read_integer("Введите N для суммы нечётных чисел: ")  # Получаем границу диапазона нечётных чисел.
    odd_sum = sum(number for number in range(1, limit + 1) if number % 2 != 0)  # Складываем только нечётные числа от одного до N.
    print(f"Сумма нечётных чисел от 1 до {limit}: {odd_sum}")  # Выводим рассчитанную сумму нечётных чисел.

    print("\nЗадание 5. Возведение в степень")  # Начинаем задания на возведение чисел в степень.
    number = read_integer("Введите число для возведения в квадрат: ")  # Получаем число для вычисления квадрата.
    print(f"{number} в квадрате: {number**2}")  # Вычисляем и выводим вторую степень числа.
    number = read_integer("Введите число для возведения в куб: ")  # Получаем число для вычисления куба.
    print(f"{number} в кубе: {number**3}")  # Вычисляем и выводим третью степень числа.
    number = read_integer("Введите основание степени: ")  # Получаем основание произвольной степени.
    exponent = read_integer("Введите степень: ")  # Получаем показатель произвольной степени.
    print(f"{number} в степени {exponent}: {number**exponent}")  # Вычисляем и выводим указанную степень.
    exponent = read_integer("Введите степень для числа 2: ")  # Получаем показатель степени числа два.
    print(f"2 в степени {exponent}: {2**exponent}")  # Вычисляем и выводим указанную степень двойки.

    print("\nЗадание 6. Проверка возраста")  # Начинаем задания на проверку возрастных условий.
    age = read_nonnegative_integer("Введите возраст для проверки совершеннолетия: ")  # Получаем неотрицательный возраст.
    print("Совершеннолетний." if age >= 18 else "Несовершеннолетний.")  # Проверяем достижение восемнадцати лет.
    age = read_nonnegative_integer("Введите возраст для проверки пенсионного возраста: ")  # Получаем возраст для проверки порога 65 лет.
    print("Пенсионный возраст достигнут." if age >= 65 else "Пенсионный возраст не достигнут.")  # Проверяем достижение пенсионного возраста.
    age = read_nonnegative_integer("Введите возраст для проверки школьного диапазона: ")  # Получаем возраст для проверки школьного диапазона.
    print("Возраст подходит для школы." if 7 <= age <= 18 else "Возраст не подходит для школы.")  # Проверяем включительный диапазон от семи до восемнадцати лет.
    age = read_nonnegative_integer("Введите возраст для проверки круглого десятка: ")  # Получаем возраст для проверки кратности десяти.
    print("Возраст является круглым десятком." if age % 10 == 0 else "Возраст не является круглым десятком.")  # Проверяем остаток от деления возраста на десять.

    print("\nЗадание 7. Факториал числа")  # Начинаем задания на вычисление факториала.
    print(f"Факториал числа 3: {math.factorial(3)}")  # Вычисляем и выводим заранее заданный факториал трёх.
    print(f"Факториал числа 5: {math.factorial(5)}")  # Вычисляем и выводим заранее заданный факториал пяти.
    number = read_nonnegative_integer("Введите N для вычисления факториала: ")  # Получаем допустимое неотрицательное число.
    print(f"Факториал числа {number}: {math.factorial(number)}")  # Вычисляем и выводим факториал введённого числа.
    while True:  # Повторяем расчёт факториалов до ввода нуля пользователем.
        number = read_integer("Введите число для факториала (0 — завершить): ")  # Считываем очередное число или команду завершения.
        if number == 0:  # Проверяем, ввёл ли пользователь ноль для завершения цикла.
            print("Ввод факториалов завершён.")  # Подтверждаем штатное завершение этого задания.
            break  # Выходим из цикла после ввода сигнального нуля.
        if number < 0:  # Проверяем, не введено ли отрицательное число.
            print("Факториал отрицательного числа не определён.")  # Сообщаем, что факториал отрицательного числа не поддерживается.
            continue  # Переходим к следующему запросу без вычисления.
        print(f"Факториал числа {number}: {math.factorial(number)}")  # Вычисляем и выводим факториал положительного числа.

    print("\nЗадание 8. Работа с цифрами числа")  # Начинаем задания на обработку цифр чисел.
    number = read_number_with_digits("Введите двузначное число для суммы цифр: ", 2)  # Получаем целое число ровно из двух цифр.
    digits = [int(digit) for digit in str(abs(number))]  # Получаем отдельные цифры модуля числа.
    print(f"Сумма цифр числа {number}: {sum(digits)}")  # Складываем и выводим цифры двузначного числа.
    number = read_number_with_digits("Введите двузначное число для произведения цифр: ", 2)  # Получаем другое двузначное целое число.
    digits = [int(digit) for digit in str(abs(number))]  # Преобразуем цифры модуля числа в целые значения.
    digit_product = math.prod(digits)  # Перемножаем все цифры числа.
    print(f"Произведение цифр числа {number}: {digit_product}")  # Выводим вычисленное произведение цифр.
    number = read_number_with_digits("Введите трёхзначное число для суммы цифр: ", 3)  # Получаем целое число ровно из трёх цифр.
    digits = [int(digit) for digit in str(abs(number))]  # Получаем все цифры модуля трёхзначного числа.
    print(f"Сумма цифр числа {number}: {sum(digits)}")  # Складываем и выводим цифры трёхзначного числа.
    number = read_number_with_digits("Введите трёхзначное число для вывода первой и последней цифр: ", 3)  # Получаем трёхзначное число для выделения крайних цифр.
    digits = str(abs(number))  # Представляем модуль числа строкой для обращения к отдельным цифрам.
    print(f"Первая цифра: {digits[0]}, последняя цифра: {digits[-1]}")  # Выводим первую и последнюю цифры введённого числа.

    print("\nЗадание 9. Проверка символа")  # Начинаем задания на проверку введённого символа.
    character = read_character("Введите один символ для проверки цифры: ")  # Получаем ровно один символ для проверки цифры.
    print("Это цифра." if character.isdigit() else "Это не цифра.")  # Проверяем, является ли символ десятичной цифрой.
    character = read_character("Введите один символ для проверки буквы: ")  # Получаем один символ для проверки буквы.
    print("Это буква." if character.isalpha() else "Это не буква.")  # Проверяем, является ли символ буквой.
    character = read_character("Введите один символ для проверки гласной: ").lower()  # Получаем символ и приводим букву к нижнему регистру.
    vowels = "аеёиоуыэюяaeiou"  # Перечисляем русские и английские гласные буквы.
    print("Это гласная буква." if character in vowels else "Это не гласная буква.")  # Проверяем наличие символа среди гласных.
    character = read_character("Введите один символ для проверки прописной буквы: ")  # Получаем символ для проверки верхнего регистра.
    print("Это прописная буква." if character.isalpha() and character.isupper() else "Это не прописная буква.")  # Проверяем, что символ является буквой в верхнем регистре.

    print("\nЗадание 10. Циклы с условием")  # Начинаем задания с циклами и условиями завершения.
    total = 0  # Создаём накопитель суммы для задания с нулём-сентинелом.
    while True:  # Повторяем ввод чисел, пока не будет введён ноль.
        number = read_integer("Введите число (0 — завершить): ")  # Считываем очередное целое число.
        if number == 0:  # Проверяем, введено ли условие остановки.
            break  # Прерываем ввод чисел после нуля.
        total += number  # Добавляем введённое число к сумме.
    print(f"Сумма введённых чисел: {total}")  # Выводим сумму всех чисел до сигнального нуля.
    count = 0  # Создаём счётчик чисел, введённых до отрицательного значения.
    while True:  # Повторяем ввод до получения отрицательного числа.
        number = float(input("Введите число (отрицательное — завершить): "))  # Считываем следующее вещественное число.
        if number < 0:  # Проверяем, является ли число сигналом завершения.
            break  # Завершаем цикл, не включая отрицательное число в счётчик.
        count += 1  # Считаем каждое введённое неотрицательное число, включая ноль.
    print(f"До отрицательного числа введено значений: {count}")  # Выводим количество значений до отрицательного числа.
    odd_sum = 0  # Создаём сумму нечётных чисел для следующего цикла.
    while True:  # Повторяем ввод до получения чётного числа.
        number = read_integer("Введите число (чётное — завершить): ")  # Считываем очередное целое число.
        if number % 2 == 0:  # Проверяем, является ли число чётным сигналом завершения.
            break  # Завершаем цикл при первом чётном числе.
        odd_sum += number  # Добавляем нечётное число к сумме.
    print(f"Сумма введённых нечётных чисел: {odd_sum}")  # Выводим сумму нечётных чисел до чётного значения.
    total = 0.0  # Создаём вещественный накопитель чисел для вычисления среднего.
    count = 0  # Создаём счётчик чисел, включая завершающее значение больше ста.
    while True:  # Повторяем ввод чисел до получения числа больше ста.
        number = float(input("Введите число (больше 100 — завершить): "))  # Считываем очередное вещественное число.
        total += number  # Добавляем каждое введённое число к сумме, в том числе завершающее.
        count += 1  # Учитываем каждое введённое число в количестве значений.
        if number > 100:  # Проверяем условие завершения ввода.
            break  # Выходим из цикла, когда число стало больше ста.
    print(f"Среднее арифметическое введённых чисел: {total / count}")  # Вычисляем и выводим среднее арифметическое всех введённых значений.


if __name__ == "__main__":  # Проверяем, запущен ли этот файл напрямую, а не импортирован как модуль.
    main()  # Запускаем выполнение всех заданий первой лабораторной работы.
