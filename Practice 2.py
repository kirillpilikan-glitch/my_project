from functools import wraps  # Импортируем wraps, чтобы декораторы сохраняли имя и документацию исходных функций.


def logger(func):  # Объявляем декоратор, который выводит информацию о вызове и результате функции.
    @wraps(func)  # Сохраняем метаданные исходной функции у обёртки.
    def wrapper(*args, **kwargs):  # Объявляем обёртку, принимающую любые позиционные и именованные аргументы.
        print(f"Вызов функции {func.__name__} с аргументами {args} и {kwargs}")  # Выводим имя функции и переданные ей аргументы до вызова.
        result = func(*args, **kwargs)  # Вызываем исходную функцию и сохраняем её результат.
        print(f"Функция {func.__name__} вернула {result}")  # Выводим результат после успешного выполнения исходной функции.
        return result  # Возвращаем результат вызывающему коду, не изменяя поведение функции.
    return wrapper  # Возвращаем обёрнутую функцию как результат применения декоратора.


def require_role(allowed_roles):  # Объявляем декоратор-фабрику, принимающий список разрешённых ролей.
    def decorator(func):  # Создаём декоратор, который будет проверять пользователя перед выполнением функции.
        @wraps(func)  # Сохраняем имя и документацию защищаемой функции у обёртки.
        def wrapper(user, *args, **kwargs):  # Объявляем обёртку, получающую пользователя первым аргументом.
            user_name = user.get("name", "Неизвестный пользователь")  # Безопасно получаем имя для сообщения об отказе.
            user_role = user.get("role")  # Получаем роль пользователя из словаря.
            if user_role not in allowed_roles:  # Проверяем, входит ли роль пользователя в список разрешённых.
                print(f"Доступ запрещён пользователю {user_name}")  # Выводим сообщение об отказе в доступе.
                return None  # Не запускаем защищённую функцию и явно возвращаем отсутствие результата.
            return func(user, *args, **kwargs)  # Передаём управление функции только при наличии разрешённой роли.
        return wrapper  # Возвращаем функцию с проверкой роли.
    return decorator  # Возвращаем декоратор, настроенный для переданного списка ролей.


@logger  # Включаем логирование вызова и результата функции сложения.
def add(a, b):  # Объявляем функцию сложения двух чисел.
    return a + b  # Возвращаем сумму чисел.


@logger  # Включаем логирование вызова и результата функции деления.
def divide(a, b):  # Объявляем функцию деления первого числа на второе.
    if b == 0:  # Проверяем, не равен ли делитель нулю.
        raise ZeroDivisionError("Деление на ноль невозможно.")  # Явно сообщаем о недопустимой операции деления.
    return a / b  # Возвращаем частное двух чисел.


@logger  # Включаем логирование вызова и результата функции приветствия.
def greet(name):  # Объявляем функцию формирования приветствия по имени.
    return f"Привет, {name}!"  # Возвращаем приветствие в виде строки.


@require_role(["admin"])  # Разрешаем удаление базы данных только пользователям с ролью admin.
def delete_database(user):  # Объявляем демонстрационную защищённую операцию удаления базы данных.
    print(f"База данных удалена пользователем {user['name']}")  # Подтверждаем выполнение операции для администратора.
    return True  # Возвращаем признак успешного выполнения операции.


def main():  # Объявляем функцию, демонстрирующую работу всех декораторов.
    print("=" * 60)  # Выводим разделитель перед началом практической работы.
    print("ПРАКТИЧЕСКАЯ РАБОТА № 2: ДЕКОРАТОРЫ")  # Печатаем заголовок практической работы.
    print("=" * 60)  # Выводим разделитель под заголовком.
    add(10, 5)  # Вызываем декорированную функцию сложения с двумя числами.
    divide(10, 2)  # Вызываем декорированную функцию деления с ненулевым делителем.
    greet("Анна")  # Вызываем декорированную функцию приветствия.
    admin = {"name": "Алексей", "role": "admin"}  # Создаём пользователя с разрешённой ролью администратора.
    guest = {"name": "Ирина", "role": "guest"}  # Создаём пользователя с ролью, которой запрещена операция.
    delete_database(admin)  # Вызываем защищённую функцию от имени администратора.
    delete_database(guest)  # Проверяем отказ в доступе для пользователя без необходимой роли.


if __name__ == "__main__":  # Проверяем, запущен ли этот файл напрямую, а не импортирован как модуль.
    main()  # Запускаем демонстрацию декораторов при непосредственном исполнении файла.
