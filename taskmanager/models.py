"""Модель и правила проверки задачи менеджера."""  # Докстринг описывает предметную модель модуля.

from dataclasses import asdict, dataclass, replace  # Импортируем инструменты создания и копирования моделей данных.
from datetime import datetime  # Импортируем часы для фиксации времени создания задачи.


@dataclass  # Автоматически создаём инициализатор и представление объекта задачи.
class Task:  # Объявляем модель одной пользовательской задачи.
    (  # Начинаем объединение строк в полноценный многострочный docstring класса.
        "Представляет задачу менеджера.\n"  # Кратко описываем назначение класса.
        "\n"  # Добавляем разделитель между описанием и полями конструктора.
        "Args:\n"  # Начинаем Google-раздел параметров конструктора dataclass.
        "    id (int): Положительный идентификатор задачи.\n"  # Документируем ID задачи.
        "    title (str): Непустое название задачи.\n"  # Документируем название задачи.
        "    description (str): Подробное описание, по умолчанию пустое.\n"  # Документируем описание задачи.
        "    priority (int): Приоритет от 1 до 5.\n"  # Документируем приоритет.
        "    status (str): Статус todo или done.\n"  # Документируем допустимые состояния задачи.
        "    created_at (str): Дата ISO 8601 или пустая строка для автоматической даты.\n"  # Документируем время создания.
        "\n"  # Отделяем параметры от списка исключений.
        "Raises:\n"  # Начинаем Google-раздел исключений конструктора.
        "    ValueError: Если ID, название, приоритет или статус недопустимы.\n"  # Документируем проверку ограничений модели.
    )  # Python распознаёт объединённые строки как docstring класса.
    id: int  # Храним уникальный целочисленный идентификатор задачи.
    title: str  # Храним краткое название задачи.
    description: str = ""  # Храним необязательное подробное описание задачи.
    priority: int = 3  # Храним приоритет задачи от 1 (высокий) до 5 (низкий).
    status: str = "todo"  # Храним статус задачи: todo или done.
    created_at: str = ""  # Храним время создания в формате ISO 8601.

    def __post_init__(self) -> None:  # Проверяем ограничения модели после автоматической инициализации dataclass.
        (  # Начинаем многострочный docstring проверки модели.
            "Проверяет поля задачи и задаёт дату создания, если она не передана.\n"  # Описываем назначение проверки.
            "\n"  # Отделяем краткое описание от результата и исключения.
            "Returns:\n"  # Начинаем раздел результата.
            "    None: Результат проверки не возвращается.\n"  # Указываем отсутствие возвращаемого значения.
            "\n"  # Отделяем результат от исключений.
            "Raises:\n"  # Начинаем раздел исключений.
            "    ValueError: Если ID, название, приоритет или статус недопустимы.\n"  # Описываем ошибки валидации.
        )  # Python распознаёт объединённые строки как docstring метода.
        if self.id < 1:  # Проверяем, что идентификатор задачи является положительным.
            raise ValueError("Идентификатор задачи должен быть положительным числом.")  # Отклоняем недопустимый идентификатор.
        if not self.title.strip():  # Проверяем, что название не пусто и не состоит из пробелов.
            raise ValueError("Название задачи не может быть пустым.")  # Отклоняем пустое название.
        if not 1 <= self.priority <= 5:  # Проверяем, что приоритет находится в установленном диапазоне.
            raise ValueError("Приоритет должен быть числом от 1 до 5.")  # Отклоняем значение приоритета вне диапазона.
        if self.status not in {"todo", "done"}:  # Проверяем, что статус входит в набор поддерживаемых состояний.
            raise ValueError("Статус задачи должен быть todo или done.")  # Отклоняем неизвестный статус.
        if not self.created_at:  # Проверяем, было ли передано время создания задачи.
            self.created_at = datetime.now().astimezone().isoformat(timespec="seconds")  # Записываем локальное время с часовым поясом.

    def to_dict(self) -> dict[str, int | str]:  # Преобразуем объект в словарь для хранения в JSON.
        (  # Начинаем многострочный docstring сериализации модели.
            "Преобразует задачу в словарь для сериализации.\n"  # Кратко описываем действие метода.
            "\n"  # Отделяем описание от результата.
            "Returns:\n"  # Начинаем раздел возвращаемого значения.
            "    dict[str, int | str]: Значения всех полей задачи.\n"  # Документируем структуру словаря.
            "\n"  # Отделяем возвращаемое значение от возможных исключений.
            "Raises:\n"  # Начинаем раздел исключений.
            "    Исключения не ожидаются при корректно созданной модели.\n"  # Указываем, что метод не выполняет операции с ошибками.
        )  # Python распознаёт объединённые строки как docstring метода.
        return asdict(self)  # Возвращаем словарь со всеми полями dataclass.

    @classmethod  # Объявляем альтернативный конструктор, вызываемый на классе Task.
    def from_dict(cls, data: dict[str, object]) -> "Task":  # Создаём задачу из словаря, прочитанного из файла.
        (  # Начинаем многострочный docstring преобразования записи.
            "Создаёт экземпляр задачи из словаря.\n"  # Кратко описываем назначение альтернативного конструктора.
            "\n"  # Отделяем описание от аргументов.
            "Args:\n"  # Начинаем раздел аргументов.
            "    data (dict[str, object]): Запись задачи с полями модели.\n"  # Документируем словарь входных данных.
            "\n"  # Отделяем аргументы от результата.
            "Returns:\n"  # Начинаем раздел результата.
            "    Task: Проверенный экземпляр задачи.\n"  # Документируем возвращаемую модель.
            "\n"  # Отделяем результат от возможных исключений.
            "Raises:\n"  # Начинаем раздел исключений.
            "    KeyError: Если отсутствует обязательный ключ.\n"  # Документируем отсутствие обязательного поля.
            "    TypeError: Если значение нельзя преобразовать к полю модели.\n"  # Документируем ошибочный тип входного значения.
            "    ValueError: Если значение нарушает ограничения модели.\n"  # Документируем ошибки валидации полей.
        )  # Python распознаёт объединённые строки как docstring метода класса.
        return cls(  # Создаём экземпляр модели с проверкой полей в __post_init__.
            id=int(data["id"]),  # Преобразуем идентификатор из загруженного значения в целое число.
            title=str(data["title"]),  # Преобразуем название задачи в строку.
            description=str(data.get("description", "")),  # Берём описание или пустую строку для старых записей.
            priority=int(data.get("priority", 3)),  # Берём сохранённый приоритет или значение по умолчанию.
            status=str(data.get("status", "todo")),  # Берём сохранённый статус или начальное состояние.
            created_at=str(data.get("created_at", "")),  # Берём сохранённое время или позволяем модели создать его.
        )  # Возвращаем полностью проверенный объект задачи.

    def mark_done(self) -> "Task":  # Создаём копию задачи в завершённом состоянии.
        (  # Начинаем многострочный docstring смены статуса задачи.
            "Возвращает копию задачи в завершённом состоянии.\n"  # Кратко описываем назначение метода.
            "\n"  # Отделяем описание от результата.
            "Returns:\n"  # Начинаем раздел возвращаемого значения.
            "    Task: Новая задача с теми же полями и статусом done.\n"  # Документируем возвращаемую копию.
            "\n"  # Отделяем результат от исключений.
            "Raises:\n"  # Начинаем раздел исключений.
            "    ValueError: Если поля исходной задачи недопустимы.\n"  # Документируем ошибку проверки создаваемой модели.
        )  # Python распознаёт объединённые строки как docstring метода.
        return replace(self, status="done")  # Возвращаем новый объект, сохраняя исходные остальные поля.
