"""Создание интерфейса командной строки менеджера задач."""  # Докстринг описывает запуск CLI приложения.

import argparse  # Импортируем argparse для разбора флагов командной строки.
from pathlib import Path  # Импортируем Path для настройки файла данных.
from collections.abc import Sequence  # Импортируем тип последовательности аргументов для аннотации функции запуска.

from taskmanager import __version__  # Импортируем текущую версию приложения.
from taskmanager.commands import run_command  # Импортируем обработчик выбранной команды.


def build_parser() -> argparse.ArgumentParser:  # Создаём парсер флагов приложения-менеджера задач.
    (  # Начинаем многострочный docstring настройки argparse.
        "Создаёт парсер аргументов консольного менеджера задач.\n"  # Кратко описываем назначение функции настройки CLI.
        "\n"  # Отделяем описание от результата.
        "Returns:\n"  # Начинаем раздел возвращаемого значения.
        "    argparse.ArgumentParser: Парсер команд, фильтров и пути к базе.\n"  # Документируем настроенный объект.
        "\n"  # Отделяем результат от особенностей argparse.
        "Raises:\n"  # Начинаем раздел исключений.
        "    SystemExit: argparse завершает процесс при запросе справки или ошибке аргументов.\n"  # Документируем автоматические выходы парсера.
    )  # Python распознаёт объединённые строки как docstring функции.
    parser = argparse.ArgumentParser(prog="taskmanager", description="Консольный менеджер задач.")  # Настраиваем имя команды и краткое описание программы.
    actions = parser.add_mutually_exclusive_group(required=True)  # Требуем ровно один режим работы при каждом запуске.
    actions.add_argument("--add", metavar="НАЗВАНИЕ", help="Добавить новую задачу.")  # Добавляем команду создания задачи.
    actions.add_argument("--list", action="store_true", help="Показать задачи.")  # Добавляем команду просмотра списка.
    actions.add_argument("--done", type=int, metavar="ID", help="Завершить задачу по ID.")  # Добавляем команду завершения задачи.
    actions.add_argument("--delete", type=int, metavar="ID", help="Удалить задачу по ID.")  # Добавляем команду удаления задачи.
    parser.add_argument("--description", default="", help="Описание новой задачи.")  # Добавляем необязательное описание для новой задачи.
    parser.add_argument("--priority", type=int, choices=range(1, 6), default=3, help="Приоритет от 1 (высокий) до 5 (низкий).")  # Добавляем валидацию приоритета задачи.
    parser.add_argument("--status", choices=("todo", "done"), help="Фильтр списка по статусу.")  # Добавляем фильтр списка по статусу.
    parser.add_argument("--filter-priority", type=int, choices=range(1, 6), help="Фильтр списка по приоритету.")  # Добавляем фильтр списка по приоритету.
    parser.add_argument("--database", "--db", dest="database", type=Path, default=Path("tasks.sqlite3"), help="Путь к файлу базы данных SQLite.")  # Добавляем путь к базе данных с короткой альтернативной опцией.
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")  # Добавляем стандартный вывод версии и завершение.
    return parser  # Возвращаем готовый парсер вызывающему коду.


def main(argv: Sequence[str] | None = None) -> int:  # Разбираем аргументы и запускаем соответствующую команду менеджера.
    (  # Начинаем многострочный docstring главной функции CLI.
        "Разбирает параметры и запускает выбранную операцию менеджера.\n"  # Кратко описываем сценарий работы функции.
        "\n"  # Отделяем описание от аргументов.
        "Args:\n"  # Начинаем раздел параметров.
        "    argv (Sequence[str] | None): Аргументы без имени программы или None для sys.argv.\n"  # Документируем источник аргументов.
        "\n"  # Отделяем параметры от результата.
        "Returns:\n"  # Начинаем раздел результата.
        "    int: Код завершения выбранной команды.\n"  # Документируем результат диспетчеризации.
        "\n"  # Отделяем результат от исключений.
        "Raises:\n"  # Начинаем раздел исключений.
        "    SystemExit: argparse обрабатывает справку, версию или ошибочные аргументы.\n"  # Документируем поведение стандартного парсера.
    )  # Python распознаёт объединённые строки как docstring функции.
    parser = build_parser()  # Создаём единый парсер всех команд.
    args = parser.parse_args(argv)  # Разбираем переданный список или системные аргументы командной строки.
    return run_command(args, args.database)  # Запускаем обработчик и возвращаем его код завершения.
