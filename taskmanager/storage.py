"""Создание SQLite-схемы и выполнение SQL-операций над задачами."""  # Докстринг описывает слой постоянного хранения данных.

import sqlite3  # Импортируем стандартный модуль SQLite для подключения и выполнения SQL-запросов.
from contextlib import closing  # Импортируем closing для гарантированного закрытия соединений.
from pathlib import Path  # Импортируем Path для работы с файлом базы данных.

from taskmanager.models import Task  # Импортируем модель задачи для преобразования строк таблицы.


def _open_database(path: Path) -> sqlite3.Connection:  # Создаём соединение SQLite и инициализируем таблицу при необходимости.
    (  # Начинаем многострочный docstring инициализации базы.
        "Открывает базу SQLite и создаёт таблицу задач при необходимости.\n"  # Кратко описываем инициализацию базы данных.
        "\n"  # Отделяем описание от аргументов.
        "Args:\n"  # Начинаем раздел аргументов.
        "    path (Path): Путь к файлу базы данных SQLite.\n"  # Документируем путь к базе.
        "\n"  # Отделяем аргументы от результата.
        "Returns:\n"  # Начинаем раздел результата.
        "    sqlite3.Connection: Соединение с созданной таблицей tasks.\n"  # Документируем возвращаемое соединение.
        "\n"  # Отделяем результат от исключений.
        "Raises:\n"  # Начинаем раздел исключений.
        "    OSError: Если невозможно создать каталог базы данных.\n"  # Документируем ошибку файловой системы.
        "    sqlite3.Error: Если SQLite не может открыть базу или создать таблицу.\n"  # Документируем SQL-ошибку инициализации.
    )  # Python распознаёт объединённые строки как docstring функции.
    path.parent.mkdir(parents=True, exist_ok=True)  # Создаём родительские каталоги файла базы, если их ещё нет.
    connection = sqlite3.connect(path)  # Открываем базу данных или создаём новый файл SQLite.
    try:  # Закрываем соединение, если начальная настройка схемы завершится ошибкой SQLite.
        connection.row_factory = sqlite3.Row  # Настраиваем доступ к столбцам строки по именам.
        connection.execute(  # Создаём таблицу задач, если она ещё не была создана.
            """CREATE TABLE IF NOT EXISTS tasks (id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT NOT NULL CHECK (length(trim(title)) > 0), description TEXT NOT NULL DEFAULT '', priority INTEGER NOT NULL CHECK (priority BETWEEN 1 AND 5), status TEXT NOT NULL CHECK (status IN ('todo', 'done')), created_at TEXT NOT NULL)"""  # Объявляем SQL-схему задач с ограничениями целостности.
        )  # Выполняем запрос создания таблицы.
        connection.commit()  # Фиксируем создание таблицы в файле базы данных.
    except sqlite3.Error:  # Перехватываем только ошибки операций SQLite во время настройки.
        connection.close()  # Освобождаем ресурс соединения перед передачей ошибки вызывающему коду.
        raise  # Повторно возбуждаем исходную ошибку, не скрывая причину сбоя.
    return connection  # Возвращаем готовое соединение вызывающей функции.


def add_task(path: Path, title: str, description: str = "", priority: int = 3) -> Task:  # Добавляем запись о задаче с помощью параметризованного SQL-запроса.
    (  # Начинаем многострочный docstring добавления задачи.
        "Добавляет задачу в SQLite параметризованным SQL-запросом.\n"  # Кратко описываем операцию вставки.
        "\n"  # Отделяем описание от аргументов.
        "Args:\n"  # Начинаем раздел аргументов.
        "    path (Path): Путь к файлу SQLite.\n"  # Документируем расположение базы.
        "    title (str): Непустое название задачи.\n"  # Документируем заголовок новой задачи.
        "    description (str): Подробное описание, по умолчанию пустое.\n"  # Документируем описание задачи.
        "    priority (int): Приоритет от 1 до 5, по умолчанию 3.\n"  # Документируем важность задачи.
        "\n"  # Отделяем аргументы от результата.
        "Returns:\n"  # Начинаем раздел результата.
        "    Task: Созданная и сохранённая задача с ID из SQLite.\n"  # Документируем возвращаемый объект.
        "\n"  # Отделяем результат от исключений.
        "Raises:\n"  # Начинаем раздел исключений.
        "    OSError: Если файл базы недоступен.\n"  # Документируем ошибку доступа к файлу.
        "    sqlite3.Error: Если SQL-запрос завершился ошибкой.\n"  # Документируем ошибку SQLite.
        "    ValueError: Если поля задачи недопустимы.\n"  # Документируем валидацию модели.
    )  # Python распознаёт объединённые строки как docstring функции.
    candidate = Task(id=1, title=title, description=description, priority=priority)  # Проверяем входные поля модели и получаем время создания.
    with closing(_open_database(path)) as connection:  # Открываем базу и гарантируем закрытие соединения после операции.
        with connection:  # Начинаем транзакцию, которая автоматически фиксируется или откатывается.
            cursor = connection.execute(  # Выполняем параметризованную вставку без конкатенации пользовательского SQL.
                "INSERT INTO tasks (title, description, priority, status, created_at) VALUES (?, ?, ?, ?, ?)",  # Подготавливаем запрос добавления новой задачи.
                (candidate.title, candidate.description, candidate.priority, candidate.status, candidate.created_at),  # Передаём значения как параметры SQL.
            )  # Завершаем выполнение вставки.
            task_id = cursor.lastrowid  # Получаем уникальный идентификатор, назначенный SQLite.
            if task_id is None:  # Проверяем, что база действительно вернула идентификатор новой строки.
                raise sqlite3.DatabaseError("SQLite не вернула идентификатор созданной задачи.")  # Явно сообщаем о невозможном результате INSERT.
    return Task(id=task_id, title=candidate.title, description=candidate.description, priority=candidate.priority, status=candidate.status, created_at=candidate.created_at)  # Возвращаем модель с реальным ID из базы.


def update_task(path: Path, task_id: int, *, done: bool) -> Task:  # Меняем статус выбранной задачи и возвращаем обновлённую запись.
    (  # Начинаем многострочный docstring обновления задачи.
        "Изменяет статус задачи в таблице и возвращает актуальную запись.\n"  # Кратко описываем SQL-обновление.
        "\n"  # Отделяем описание от аргументов.
        "Args:\n"  # Начинаем раздел аргументов.
        "    path (Path): Путь к файлу SQLite.\n"  # Документируем расположение базы.
        "    task_id (int): Идентификатор изменяемой задачи.\n"  # Документируем ID записи.
        "    done (bool): Если True, отметить задачу выполненной.\n"  # Документируем флаг смены статуса.
        "\n"  # Отделяем аргументы от результата.
        "Returns:\n"  # Начинаем раздел результата.
        "    Task: Обновлённая задача.\n"  # Документируем возвращаемую запись.
        "\n"  # Отделяем результат от исключений.
        "Raises:\n"  # Начинаем раздел исключений.
        "    KeyError: Если задача с указанным ID не найдена.\n"  # Документируем отсутствие ID.
        "    OSError: Если файл базы недоступен.\n"  # Документируем ошибку файловой системы.
        "    sqlite3.Error: Если SQL-запрос завершился ошибкой.\n"  # Документируем ошибку базы.
    )  # Python распознаёт объединённые строки как docstring функции.
    with closing(_open_database(path)) as connection:  # Открываем соединение с гарантированным закрытием после операции.
        with connection:  # Объединяем выбор и обновление записи в одну транзакцию.
            row = connection.execute("SELECT * FROM tasks WHERE id = ?", (task_id,)).fetchone()  # Находим задачу параметризованным запросом.
            if row is None:  # Проверяем, существует ли запись с переданным идентификатором.
                raise KeyError(f"Задача с ID {task_id} не найдена.")  # Возвращаем понятную ошибку отсутствующей задачи.
            task = Task.from_dict(dict(row))  # Преобразуем найденную строку SQLite в проверенную модель Task.
            updated_task = task.mark_done() if done else task  # Создаём завершённую задачу, если включён флаг done.
            connection.execute("UPDATE tasks SET status = ? WHERE id = ?", (updated_task.status, task_id))  # Сохраняем новый статус с параметрами SQL.
    return updated_task  # Возвращаем обновлённую задачу вызывающему коду.


def delete_task(path: Path, task_id: int) -> Task:  # Удаляем запись SQLite и возвращаем удалённую задачу.
    (  # Начинаем многострочный docstring удаления задачи.
        "Удаляет задачу из SQLite и возвращает удалённые данные.\n"  # Кратко описываем операцию удаления.
        "\n"  # Отделяем описание от аргументов.
        "Args:\n"  # Начинаем раздел аргументов.
        "    path (Path): Путь к файлу SQLite.\n"  # Документируем расположение базы.
        "    task_id (int): Идентификатор удаляемой задачи.\n"  # Документируем ID записи.
        "\n"  # Отделяем аргументы от результата.
        "Returns:\n"  # Начинаем раздел результата.
        "    Task: Удалённая задача.\n"  # Документируем сохранённое описание удалённой записи.
        "\n"  # Отделяем результат от исключений.
        "Raises:\n"  # Начинаем раздел исключений.
        "    KeyError: Если задача с указанным ID не найдена.\n"  # Документируем ошибку отсутствующего объекта.
        "    OSError: Если файл базы недоступен.\n"  # Документируем ошибку доступа к файлу базы.
        "    sqlite3.Error: Если SQL-запрос завершился ошибкой.\n"  # Документируем ошибки SQLite.
    )  # Python распознаёт объединённые строки как docstring функции.
    with closing(_open_database(path)) as connection:  # Открываем базу и гарантируем закрытие соединения.
        with connection:  # Гарантируем атомарность чтения и удаления записи.
            row = connection.execute("SELECT * FROM tasks WHERE id = ?", (task_id,)).fetchone()  # Получаем удаляемую запись параметризованным запросом.
            if row is None:  # Проверяем, найден ли заданный ID.
                raise KeyError(f"Задача с ID {task_id} не найдена.")  # Сообщаем, что удалять нечего.
            deleted_task = Task.from_dict(dict(row))  # Сохраняем копию модели перед удалением строки из базы.
            connection.execute("DELETE FROM tasks WHERE id = ?", (task_id,))  # Удаляем строку по ID безопасным SQL-параметром.
    return deleted_task  # Возвращаем данные задачи, удалённой из базы.


def list_tasks(path: Path, status: str | None = None, priority: int | None = None) -> list[Task]:  # Получаем задачи с необязательной фильтрацией на стороне SQLite.
    (  # Начинаем многострочный docstring SQL-выборки задач.
        "Возвращает задачи, удовлетворяющие необязательным фильтрам.\n"  # Кратко описываем назначение выборки.
        "\n"  # Отделяем описание от аргументов.
        "Args:\n"  # Начинаем раздел аргументов.
        "    path (Path): Путь к файлу SQLite.\n"  # Документируем расположение базы.
        "    status (str | None): Фильтр todo или done либо None для всех статусов.\n"  # Документируем фильтр статуса.
        "    priority (int | None): Фильтр 1-5 либо None для любого приоритета.\n"  # Документируем фильтр важности.
        "\n"  # Отделяем аргументы от результата.
        "Returns:\n"  # Начинаем раздел результата.
        "    list[Task]: Задачи, соответствующие всем переданным фильтрам.\n"  # Документируем возвращаемый список.
        "\n"  # Отделяем результат от исключений.
        "Raises:\n"  # Начинаем раздел исключений.
        "    OSError: Если файл базы недоступен.\n"  # Документируем ошибку файловой системы.
        "    sqlite3.Error: Если SQL-запрос завершился ошибкой.\n"  # Документируем ошибку выполнения запроса.
        "    ValueError: Если значение фильтра статуса или приоритета недопустимо.\n"  # Документируем неправильные фильтры.
    )  # Python распознаёт объединённые строки как docstring функции.
    conditions = []  # Создаём список условий SQL для установленных фильтров.
    parameters = []  # Создаём список значений, которые будут переданы отдельно от SQL-текста.
    if status is not None:  # Проверяем, передал ли пользователь фильтр статуса.
        if status not in {"todo", "done"}:  # Проверяем допустимость значения статуса.
            raise ValueError("Статус должен быть todo или done.")  # Отклоняем недопустимое условие до выполнения SQL-запроса.
        conditions.append("status = ?")  # Добавляем безопасное условие сравнения статуса.
        parameters.append(status)  # Добавляем значение статуса в список параметров запроса.
    if priority is not None:  # Проверяем, передал ли пользователь фильтр приоритета.
        if not 1 <= priority <= 5:  # Проверяем поддерживаемый диапазон приоритета.
            raise ValueError("Приоритет должен быть числом от 1 до 5.")  # Отклоняем приоритет вне диапазона.
        conditions.append("priority = ?")  # Добавляем безопасное условие сравнения приоритета.
        parameters.append(priority)  # Добавляем значение приоритета в список параметров запроса.
    query = "SELECT * FROM tasks"  # Создаём базовый запрос, выбирающий все задачи.
    if conditions:  # Проверяем, нужно ли применить одно или несколько условий фильтрации.
        query += " WHERE " + " AND ".join(conditions)  # Объединяем заранее заданные условия, значения по-прежнему передаются отдельно.
    query += " ORDER BY id"  # Сортируем результаты по ID для стабильного порядка вывода.
    with closing(_open_database(path)) as connection:  # Открываем базу и гарантируем закрытие после чтения.
        rows = connection.execute(query, parameters).fetchall()  # Выполняем выборку с параметрами и получаем все найденные строки.
    return [Task.from_dict(dict(row)) for row in rows]  # Преобразуем строки базы в список объектов модели.
