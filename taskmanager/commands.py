"""Обработка операций менеджера задач и вывод их результатов."""  # Докстринг описывает уровень команд приложения.

import sqlite3  # Импортируем исключения SQLite для явного сообщения об ошибках базы.
from pathlib import Path  # Импортируем Path для типа пути к файлу хранилища.

from taskmanager.models import Task  # Импортируем модель для типизации и форматирования результатов.
from taskmanager.storage import add_task, delete_task, list_tasks, update_task  # Импортируем операции над постоянным хранилищем.


def format_task(task: Task) -> str:  # Преобразуем задачу в удобную однострочную запись для консоли.
    (  # Начинаем многострочный docstring форматирования задачи.
        "Форматирует задачу для однострочного вывода в консоль.\n"  # Кратко описываем форматирующую функцию.
        "\n"  # Отделяем описание от аргументов.
        "Args:\n"  # Начинаем раздел аргументов.
        "    task (Task): Задача, которую требуется отобразить.\n"  # Документируем исходную модель.
        "\n"  # Отделяем аргументы от результата.
        "Returns:\n"  # Начинаем раздел результата.
        "    str: Строка с ID, названием, статусом, приоритетом и описанием.\n"  # Документируем формат результата.
        "\n"  # Отделяем результат от исключений.
        "Raises:\n"  # Начинаем раздел исключений.
        "    Исключения не ожидаются при корректно созданной модели.\n"  # Указываем отсутствие ожидаемых ошибок.
    )  # Python распознаёт объединённые строки как docstring функции.
    return f"[{task.id}] {task.title} | статус: {task.status} | приоритет: {task.priority} | {task.description}"  # Возвращаем ключевые поля задачи в читаемом формате.


def run_command(args, storage_path: Path) -> int:  # Выполняем выбранную команду и печатаем результат её обработки.
    (  # Начинаем многострочный docstring диспетчера CLI-команд.
        "Выполняет выбранную команду менеджера задач и печатает результат.\n"  # Кратко описываем обработчик команд.
        "\n"  # Отделяем описание от аргументов.
        "Args:\n"  # Начинаем раздел аргументов.
        "    args (argparse.Namespace): Проверенные параметры командной строки.\n"  # Документируем объект разбора аргументов.
        "    storage_path (Path): Путь к файлу базы SQLite.\n"  # Документируем расположение постоянного хранилища.
        "\n"  # Отделяем аргументы от результата.
        "Returns:\n"  # Начинаем раздел результата.
        "    int: Код 0 при успехе и 1 при обработанной ошибке.\n"  # Документируем результат для вызывающего процесса.
        "\n"  # Отделяем результат от ожидаемых исключений.
        "Raises:\n"  # Начинаем раздел ошибок.
        "    Ошибки модели и базы выводятся пользователю и преобразуются в код 1.\n"  # Документируем обработку исключений внутри команды.
    )  # Python распознаёт объединённые строки как docstring функции.
    try:  # Перехватываем ошибки предметной области и некорректные данные хранилища.
        if args.add is not None:  # Проверяем, выбран ли режим добавления задачи.
            task = add_task(storage_path, args.add, args.description, args.priority)  # Создаём задачу с переданными параметрами.
            print(f"Добавлена задача: {format_task(task)}")  # Подтверждаем добавление и показываем созданную запись.
        elif args.list:  # Проверяем, выбран ли режим отображения списка задач.
            tasks = list_tasks(storage_path, status=args.status, priority=args.filter_priority)  # Загружаем задачи с указанными фильтрами.
            if not tasks:  # Проверяем, остались ли записи после загрузки и фильтрации.
                print("Задачи не найдены.")  # Выводим понятное сообщение для пустого списка.
            for task in tasks:  # Перебираем задачи, соответствующие фильтрам.
                print(format_task(task))  # Выводим очередную задачу.
        elif args.done is not None:  # Проверяем, выбран ли режим завершения задачи.
            task = update_task(storage_path, args.done, done=True)  # Сохраняем завершённый статус задачи с указанным ID.
            print(f"Задача завершена: {format_task(task)}")  # Подтверждаем изменение состояния задачи.
        elif args.delete is not None:  # Проверяем, выбран ли режим удаления задачи.
            task = delete_task(storage_path, args.delete)  # Удаляем задачу с указанным ID из файла.
            print(f"Удалена задача: {format_task(task)}")  # Подтверждаем удаление найденной задачи.
        return 0  # Возвращаем код успешного завершения команды.
    except (KeyError, ValueError, OSError, sqlite3.Error) as error:  # Обрабатываем ошибки задачи, модели, файловой системы и SQL.
        print(f"Ошибка: {error}")  # Выводим точную причину сбоя вместо успешного сообщения.
        return 1  # Возвращаем ненулевой код для обозначения ошибки.
