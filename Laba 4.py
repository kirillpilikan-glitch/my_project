class Transport:  # Объявляем базовый класс для всех видов транспорта.
    def __init__(self, brand: str, speed: int) -> None:  # Определяем конструктор с маркой и скоростью транспорта.
        self.brand = brand  # Сохраняем марку транспортного средства в атрибут объекта.
        self.speed = speed  # Сохраняем скорость транспортного средства в километрах в час.

    def move(self) -> str:  # Определяем метод движения для общего транспорта.
        return f"Transport is moving at {self.speed} km/h"  # Возвращаем сообщение о движении транспорта с его скоростью.

    def __str__(self) -> str:  # Определяем строковое представление объекта транспорта.
        return f"Transport: {self.brand}, Speed: {self.speed}"  # Возвращаем строку с маркой и скоростью в формате из условия.


class Car(Transport):  # Объявляем класс автомобиля как наследника базового класса Transport.
    def __init__(self, brand: str, speed: int, seats: int) -> None:  # Определяем конструктор автомобиля с количеством мест.
        super().__init__(brand, speed)  # Вызываем конструктор Transport для инициализации марки и скорости.
        self.seats = seats  # Сохраняем количество пассажирских мест автомобиля.

    def honk(self) -> str:  # Определяем метод автомобильного сигнала.
        return "Beep beep!"  # Возвращаем требуемый звуковой сигнал.

    def move(self) -> str:  # Переопределяем движение для автомобиля.
        return f"Car {self.brand} is driving at {self.speed} km/h"  # Возвращаем сообщение о движении автомобиля.

    def __str__(self) -> str:  # Определяем строковое представление автомобиля.
        return f"Car: {self.brand}, Speed: {self.speed}, Seats: {self.seats}"  # Возвращаем описание автомобиля с количеством мест.

    def __len__(self) -> int:  # Определяем поведение встроенной функции len для автомобиля.
        return self.seats  # Возвращаем количество пассажирских мест автомобиля.

    def __eq__(self, other: object) -> bool:  # Определяем сравнение автомобилей оператором равенства.
        if not isinstance(other, Car):  # Проверяем, является ли второй объект автомобилем.
            return NotImplemented  # Передаём сравнение другому типу, если объект не является автомобилем.
        return self.speed == other.speed  # Считаем автомобили равными, если их скорости совпадают.

    def __add__(self, other: object) -> int:  # Определяем сложение скоростей двух автомобилей.
        if not isinstance(other, Car):  # Проверяем, является ли слагаемый объектом класса Car.
            return NotImplemented  # Сообщаем Python, что сложение с таким типом не поддерживается.
        return self.speed + other.speed  # Возвращаем сумму скоростей двух автомобилей.


class Bike(Transport):  # Объявляем класс велосипеда как наследника базового класса Transport.
    def __init__(self, brand: str, speed: int, bike_type: str) -> None:  # Определяем конструктор велосипеда с его типом.
        super().__init__(brand, speed)  # Вызываем конструктор Transport для инициализации марки и скорости.
        self.type = bike_type  # Сохраняем тип велосипеда в атрибуте type согласно условию.

    def move(self) -> str:  # Переопределяем движение для велосипеда.
        return f"Bike {self.brand} is cycling at {self.speed} km/h"  # Возвращаем сообщение о движении велосипеда.

    def __str__(self) -> str:  # Определяем строковое представление велосипеда.
        return f"Bike: {self.brand}, Speed: {self.speed}, Type: {self.type}"  # Возвращаем описание велосипеда с типом транспорта.


def main() -> None:  # Объявляем главную функцию с примерами использования классов транспорта.
    print("=" * 60)  # Выводим верхний разделитель лабораторной работы.
    print("ЛАБОРАТОРНАЯ РАБОТА № 4: ОБЪЕКТНО-ОРИЕНТИРОВАННОЕ ПРОГРАММИРОВАНИЕ")  # Печатаем название лабораторной работы.
    print("=" * 60)  # Выводим нижний разделитель заголовка.
    print("\n1. СОЗДАНИЕ ОБЪЕКТОВ И ВЫЗОВ МЕТОДОВ")  # Начинаем демонстрацию создания транспорта и вызова методов.
    transport = Transport("Generic", 60)  # Создаём объект базового класса с маркой и скоростью.
    car = Car("Toyota", 180, 5)  # Создаём автомобиль Toyota со скоростью 180 км/ч и пятью местами.
    another_car = Car("Honda", 180, 4)  # Создаём автомобиль Honda с такой же скоростью и четырьмя местами.
    slower_car = Car("Ford", 150, 5)  # Создаём автомобиль Ford с меньшей скоростью для сравнения.
    bike = Bike("Trek", 30, "mountain")  # Создаём горный велосипед Trek со скоростью 30 км/ч.
    print(transport)  # Выводим строковое представление базового транспортного средства.
    print(transport.move())  # Вызываем и выводим метод движения базового транспорта.
    print(car)  # Выводим строковое представление автомобиля.
    print(car.move())  # Вызываем и выводим переопределённый метод движения автомобиля.
    print(car.honk())  # Вызываем и выводим звуковой сигнал автомобиля.
    print(bike)  # Выводим строковое представление велосипеда.
    print(bike.move())  # Вызываем и выводим переопределённый метод движения велосипеда.
    print("\n2. МАГИЧЕСКИЕ МЕТОДЫ КЛАССА CAR")  # Начинаем демонстрацию магических методов автомобиля.
    print(f"Количество мест в автомобиле: {len(car)}")  # Вызываем __len__ автомобиля через встроенную функцию len.
    print(f"Скорости автомобилей равны: {car == another_car}")  # Сравниваем автомобили по скорости с помощью __eq__.
    print(f"Скорости автомобилей равны: {car == slower_car}")  # Показываем результат сравнения автомобилей с разной скоростью.
    print(f"Сумма скоростей двух автомобилей: {car + slower_car} km/h")  # Складываем скорости двух машин с помощью __add__.
    print("\n3. ПОПЫТКА СЛОЖИТЬ АВТОМОБИЛЬ И ВЕЛОСИПЕД")  # Начинаем демонстрацию неподдерживаемой операции с разными типами.
    try:  # Начинаем обработку ожидаемой ошибки при сложении несовместимых объектов.
        mixed_sum = car + bike  # Пытаемся сложить автомобиль и велосипед.
        print(f"Результат сложения: {mixed_sum}")  # Выводим результат только в случае, если операция поддерживается.
    except TypeError as error:  # Перехватываем TypeError, возникающую при неподдерживаемом сложении.
        print(f"Операция не выполнена: {error}")  # Выводим текст ошибки, объясняющий причину отказа.
        print("Сложение не определено: метод Car.__add__ складывает скорость только с другим объектом Car.")  # Объясняем, что операция сложения реализована лишь для двух автомобилей.
    print("\n4. ПОЛИМОРФИЗМ")  # Начинаем демонстрацию полиморфизма метода движения.
    vehicles = [transport, car, another_car, bike]  # Собираем базовый объект, автомобили и велосипед в общий список.
    for vehicle in vehicles:  # Перебираем разные транспортные объекты одной общей последовательностью.
        print(vehicle.move())  # Вызываем move у каждого объекта, получая реализацию его фактического класса.


if __name__ == "__main__":  # Проверяем, запущен ли этот файл напрямую, а не импортирован как модуль.
    main()  # Запускаем главную функцию при непосредственном исполнении скрипта.
